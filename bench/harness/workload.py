"""The ``Request`` type, and loading / selecting the requests of a workload.

Workloads are generated by ``bench/workloads/generate.py``; this module only reads them.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

from bench.harness.config import WORKLOADS_DIR, HarnessError


@dataclass(frozen=True)
class Request:
    """One request of a workload (fields documented in ``bench/workloads/generate.py``)."""

    id: str
    messages: list[dict[str, str]]
    max_tokens: int  # exact output length: the harness forces the server to generate it all
    prompt_tokens: int | None = None
    session_id: str | None = None  # W4: turns of one session are sent in order
    turn: int = 0

    @classmethod
    def from_dict(cls, d: dict[str, Any]) -> Request:
        return cls(
            id=str(d["id"]),
            messages=d["messages"],
            max_tokens=int(d["max_tokens"]),
            prompt_tokens=d.get("prompt_tokens"),
            session_id=d.get("session_id"),
            turn=int(d.get("turn", 0)),
        )

    @property
    def is_single_turn(self) -> bool:
        return len(self.messages) == 1 and self.messages[0]["role"] == "user"


def load_workload(name: str | None = None, path: Path | None = None) -> tuple[str, list[Request]]:
    """``(name, requests)`` of ``bench/workloads/<name>``, or of an explicit jsonl ``path``.

    A named workload is checked against the sha256 in its ``manifest.json``.
    """
    if path is None:
        if name is None:
            raise HarnessError("give a workload name or a workload file")
        path = WORKLOADS_DIR / name / "requests.jsonl"
        if not path.exists():
            raise HarnessError(f"{path} missing: run `make workloads`")
        manifest = path.with_name("manifest.json")
        if manifest.exists():
            expected = json.loads(manifest.read_text())["sha256"]
            actual = hashlib.sha256(path.read_bytes()).hexdigest()
            if actual != expected:
                raise HarnessError(f"{path}: sha256 {actual} != manifest {expected}; regenerate")
    lines = path.read_text().splitlines()
    return name or path.stem, [Request.from_dict(json.loads(line)) for line in lines if line]


# --num-requests auto: enough requests to keep every concurrency slot busy for several rounds,
# capped so that a level at concurrency 1 does not take hours (docs/benchmarking.md).
AUTO_PER_SLOT, AUTO_MIN, AUTO_MAX = 8, 64, 512
NumRequests = int | Literal["auto"] | None  # None: the whole workload


def requests_per_run(num_requests: NumRequests, concurrency: int) -> int | None:
    """How many requests one run at ``concurrency`` sends (None = all of them)."""
    if num_requests == "auto":
        return min(AUTO_MAX, max(AUTO_MIN, AUTO_PER_SLOT * concurrency))
    return num_requests


def select_requests(requests: list[Request], n: int | None) -> list[Request]:
    """The first ``n`` requests, keeping W4 sessions whole (a session is never cut in half)."""
    if n is None or n >= len(requests):
        return requests
    selected: list[Request] = []
    started_sessions: set[str] = set()
    for r in requests:
        if r.session_id in started_sessions:
            selected.append(r)
        elif len(selected) < n:
            selected.append(r)
            if r.session_id is not None:
                started_sessions.add(r.session_id)
    return selected


def warmup_requests(n: int) -> list[Request]:
    """Synthetic requests that share no prefix with any workload request."""
    return [
        Request(
            id=f"warmup-{i}",
            messages=[{"role": "user", "content": f"Warmup {i}: count from 1 to 40."}],
            max_tokens=32,
        )
        for i in range(n)
    ]
